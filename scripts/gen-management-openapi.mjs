import { readdir, readFile, writeFile } from "node:fs/promises";
import { join, sep, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const API_DIR = join(ROOT, "app", "api", "v1");
const OUT = join(ROOT, "docs", "api", "pods-management.openapi.yaml");

const METHODS = ["GET", "POST", "PUT", "PATCH", "DELETE", "HEAD", "OPTIONS"];

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) files.push(...await walk(full));
    else if (entry.name === "route.js") files.push(full);
  }
  return files;
}

function toOpenApiPath(file) {
  const relative = file.slice(API_DIR.length).split(sep).join("/");
  return relative
    .replace(/\/route\.js$/, "")
    .replace(/\[([^\]]+)\]/g, "{$1}") || "/";
}

function methodsIn(source) {
  return METHODS.filter((method) => new RegExp(`export\\s+const\\s+${method}\\b`).test(source));
}

/**
 * Scans every management route handler and renders the path inventory.
 *
 * @returns {Promise<Array<{ path: string, methods: Array<string> }>>}
 */
export async function scanRoutes() {
  const files = await walk(API_DIR);
  const routes = [];
  for (const file of files.sort()) {
    const source = await readFile(file, "utf8");
    routes.push({ path: toOpenApiPath(file), methods: methodsIn(source), file });
  }
  return routes;
}

export function render(routes) {
  const lines = [
    "openapi: 3.1.0",
    "info:",
    "  title: Pods management API",
    "  version: 1.0.0",
    "  description: >-",
    "    Everything doable in the console is doable through this API, the",
    "    `pods` CLI and a declarative pods.yaml stack file (S14). JSON",
    "    camelCase, cursor pagination, If-Match versions, the error envelope",
    "    { error: { code, message, details? } } and x-pods-request-id (S01 §8).",
    "    Generated by scripts/gen-management-openapi.mjs — do not edit by hand.",
    "servers:",
    "  - url: /api/v1",
    "security:",
    "  - sessionCookie: []",
    "  - bearerToken: []",
    "components:",
    "  securitySchemes:",
    "    sessionCookie:",
    "      type: apiKey",
    "      in: cookie",
    "      name: pods_session",
    "    bearerToken:",
    "      type: http",
    "      scheme: bearer",
    "      bearerFormat: pods_pat_… / pods_svc_… (S14 §2)",
    "paths:",
  ];
  for (const route of routes) {
    lines.push(`  ${route.path}:`);
    for (const method of route.methods) {
      lines.push(`    ${method.toLowerCase()}:`);
      lines.push(`      operationId: ${method.toLowerCase()}_${route.path.replace(/[^A-Za-z0-9]+/g, "_").replace(/^_|_$/g, "")}`);
      lines.push(`      responses:`);
      lines.push(`        2XX:`);
      lines.push(`          description: Success envelope (JSON).`);
    }
    if (route.methods.length === 0) lines.push(`    # no exported methods found`);
  }
  return `${lines.join("\n")}\n`;
}

const invokedDirectly = process.argv[1] && fileURLToPath(import.meta.url) === join(process.argv[1]);
if (invokedDirectly) {
  const routes = await scanRoutes();
  await writeFile(OUT, render(routes), "utf8");
  console.log(`Wrote ${OUT} (${routes.length} routes).`);
}
