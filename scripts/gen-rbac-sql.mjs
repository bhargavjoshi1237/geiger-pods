// Generates the `pods.role_permissions()` SQL body from geiger-rbac.config.js
// (S02 §2). The authz_functions migration embeds the output verbatim between
// GEN-RBAC markers; tests/s02/rbac-sql.test.mjs fails on any drift.
//
// Usage: node scripts/gen-rbac-sql.mjs   (prints the function SQL to stdout)

import { fileURLToPath } from "node:url";
import { permissionKeys } from "@geiger/rbac";
import config from "../geiger-rbac.config.js";

function quoteLiteral(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

/**
 * System role key → permission patterns, straight from the catalog.
 */
export function rolePermissionMap(rbacConfig) {
  const map = {};
  for (const role of rbacConfig.systemRoles ?? []) {
    map[role.key] = [...role.permissions];
  }
  return map;
}

/**
 * `pods.role_permissions(p_role text)` as SQL. Unknown roles yield `{}` (fail
 * closed). The function is immutable: a pure mapping of versioned code.
 */
export function rolePermissionsSql(rbacConfig) {
  const known = new Set(permissionKeys(rbacConfig));
  const branches = [];
  for (const role of rbacConfig.systemRoles ?? []) {
    for (const pattern of role.permissions) {
      if (pattern !== "*" && !known.has(pattern)) {
        throw new Error(`Role "${role.key}" references unknown permission "${pattern}".`);
      }
    }
    const list = role.permissions.map(quoteLiteral).join(", ");
    branches.push(`    when ${quoteLiteral(role.key)} then array[${list}]`);
  }
  return [
    "-- Generated by scripts/gen-rbac-sql.mjs from geiger-rbac.config.js. Do not hand-edit.",
    "create or replace function pods.role_permissions(p_role text)",
    "returns text[]",
    "language sql",
    "immutable",
    "as $$",
    "  select case p_role",
    ...branches,
    "    else '{}'::text[]",
    "  end;",
    "$$;",
  ].join("\n");
}

const isMain = process.argv[1] === fileURLToPath(import.meta.url);
if (isMain) {
  process.stdout.write(`${rolePermissionsSql(config)}\n`);
}
