-- Inherited suite role for the caller, mirroring lib/workspace/access.mjs:
-- an org project maps organization_users.role (owner/admin/manager, else
-- member); an org-less project is owned by its creator; otherwise null.
create or replace function pods.inherited_role(p_project uuid)
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select case
    when p.organization_id is not null then (
      select case
        when lower(m.role) in ('owner', 'admin', 'manager') then lower(m.role)
        else 'member'
      end
      from public.organization_users m
      where m.organization = p.organization_id
        and m.user = auth.uid()
    )
    when p.created_by is not null and p.created_by = auth.uid() then 'owner'
    else null
  end
  from public.projects p
  where p.id = p_project;
$$;

