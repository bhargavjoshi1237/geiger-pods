/**
 * JavaScript SDK generator (S13 part C, native).
 *
 * ESM, fetch-based, one method per operation. Supports base URL override,
 * API key header (`x-api-key`), bearer token, a SigV4 signing hook, timeouts
 * and retries on 429/5xx with backoff.
 *
 * @module lib/sdk/javascript
 */

import { groupSdkParams, listSdkOperations, sdkMethodName } from "./operations.mjs";

/**
 * Renders the JavaScript SDK files.
 *
 * @param {{ artifact: object, invokeUrl: string|null, config: { packageName: string, version: string, className: string } }} input
 * @returns {Record<string, string>} File name → content.
 */
export function generateJavascriptFiles({ artifact, invokeUrl, config }) {
  const operations = listSdkOperations(artifact);
  const className = config.className;
  const lines = [];
  for (const operation of operations) {
    const name = sdkMethodName(operation);
    const { path: pathParams, query: queryParams, header: headerParams } = groupSdkParams(operation.requestParameters);
    const hasBody = Object.keys(operation.requestModels ?? {}).length > 0;
    lines.push(`  async ${name}(input = {}, overrides = {}) {`);
    lines.push(`    // ${operation.method} ${operation.path}`);
    if (pathParams.length > 0) {
      lines.push(`    for (const key of ${JSON.stringify(pathParams)}) {`);
      lines.push(`      if (input.params?.[key] === undefined) throw new Error(\`Missing path parameter "\${key}".\`);`);
      lines.push(`    }`);
    }
    for (const entry of [...queryParams, ...headerParams]) {
      if (entry.required) {
        const bag = queryParams.includes(entry) ? "input.params" : "input.headers";
        lines.push(`    if (${bag}?.[${JSON.stringify(entry.name)}] === undefined) throw new Error(\`Missing required parameter "${entry.name}".\`);`);
      }
    }
    lines.push(`    let resolvedPath = ${JSON.stringify(operation.path)};`);
    if (pathParams.length > 0) {
      lines.push(`    for (const key of ${JSON.stringify(pathParams)}) {`);
      lines.push(`      resolvedPath = resolvedPath.replace(\`{\${key}}\`, encodeURIComponent(String(input.params[key]))).replace(\`{\${key}+}\`, String(input.params[key]).split("/").map(encodeURIComponent).join("/"));`);
      lines.push(`    }`);
    }
    lines.push(`    const query = new URLSearchParams();`);
    lines.push(`    for (const [key, value] of Object.entries(input.params ?? {})) {`);
    lines.push(`      if (${JSON.stringify(pathParams)}.includes(key)) continue;`);
    lines.push(`      if (value === undefined || value === null) continue;`);
    lines.push(`      query.append(key, String(value));`);
    lines.push(`    }`);
    lines.push(`    const suffix = query.toString() ? \`?\${query}\` : "";`);
    lines.push(`    return this.request(resolvedPath + suffix, { method: ${JSON.stringify(operation.method)}, headers: input.headers, body: ${hasBody ? "input.body ?? null" : "null"} }, overrides);`);
    lines.push(`  }`);
    lines.push(``);
  }

  const client = `/**
 * ${config.packageName} v${config.version} — generated by Pods (S13 SDK).
 *
 * ESM fetch-based client, one method per operation. Retries on 429/5xx with
 * backoff; supports base URL override, API key header, bearer token and a
 * SigV4 signing hook (provide \`signRequest\` from your ecosystem signer).
 */
export class ${className} {
  constructor(options = {}) {
    this.baseUrl = (options.baseUrl ?? ${JSON.stringify(invokeUrl ?? "")}).replace(/\\/+$/, "");
    if (!this.baseUrl) throw new Error("A baseUrl is required (pass { baseUrl } or regenerate with an invoke URL).");
    this.apiKey = options.apiKey ?? null;
    this.bearerToken = options.bearerToken ?? null;
    this.signRequest = typeof options.signRequest === "function" ? options.signRequest : null;
    this.timeoutMs = Number.isInteger(options.timeoutMs) ? options.timeoutMs : 29000;
    this.maxRetries = Number.isInteger(options.maxRetries) ? options.maxRetries : 2;
    this.fetch = options.fetch ?? globalThis.fetch;
  }

  async request(path, { method = "GET", headers = {}, body = null } = {}, overrides = {}) {
    const url = \`\${this.baseUrl}\${path}\`;
    let attempt = 0;
    for (;;) {
      const outgoing = new Headers(headers ?? {});
      if (this.apiKey) outgoing.set("x-api-key", this.apiKey);
      if (this.bearerToken) outgoing.set("authorization", \`Bearer \${this.bearerToken}\`);
      let init = {
        method,
        headers: outgoing,
        signal: AbortSignal.timeout(this.timeoutMs),
        redirect: "manual",
      };
      if (body !== null && body !== undefined && method !== "GET" && method !== "HEAD") {
        init.body = typeof body === "string" ? body : JSON.stringify(body);
        if (!outgoing.has("content-type")) outgoing.set("content-type", "application/json");
      }
      if (this.signRequest) init = (await this.signRequest({ url, ...init })) ?? init;
      Object.assign(init, overrides.init ?? {});
      const response = await this.fetch(url, init);
      // retries on 429/5xx with backoff (honors Retry-After).
      if ((response.status === 429 || response.status >= 500) && attempt < this.maxRetries) {
        const retryAfter = Number(response.headers.get("retry-after") ?? "0");
        const backoff = Number.isFinite(retryAfter) && retryAfter > 0 ? retryAfter * 1000 : 200 * 2 ** attempt;
        await new Promise((resolve) => setTimeout(resolve, Math.min(backoff, 5000)));
        attempt += 1;
        continue;
      }
      return response;
    }
  }

${lines.join("\n")}}
`;
  const packageJson = JSON.stringify({
    name: config.packageName, version: config.version, type: "module",
    main: "client.mjs", description: `Generated Pods SDK (${config.packageName}).`,
  }, null, 2);
  return {
    "client.mjs": client,
    "package.json": `${packageJson}\n`,
    "README.md": `# ${config.packageName}\n\nGenerated by Pods (S13 SDK, javascript). Base URL override: \`new ${className}({ baseUrl })\`. API key: \`{ apiKey }\`. Bearer: \`{ bearerToken }\`. SigV4: pass \`signRequest\` from your ecosystem signer.\n`,
  };
}
