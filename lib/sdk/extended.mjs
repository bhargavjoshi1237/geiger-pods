/**
 * Extended-language SDK stubs (S13 part C, P2).
 *
 * `java`, `android`, `swift`, `ruby`, `go` and `kotlin` run through an
 * `openapi-generator` container worker (`workers/sdkgen/Dockerfile`, pinned
 * version). The control plane invokes the worker as a job; this module
 * renders the deterministic placeholder the worker replaces with the real
 * OpenAPI Generator output, so the management API stays honest about the
 * pipeline even when the worker is unavailable (tests, local dev).
 *
 * @module lib/sdk/extended
 */

export const OPENAPI_GENERATOR_VERSION = "7.8.0";

const GENERATOR_NAMES = {
  java: "java",
  android: "java (android)",
  swift: "swift5",
  ruby: "ruby",
  go: "go",
  kotlin: "kotlin",
};

const FILE_NAMES = {
  java: "Client.java",
  android: "Client.java",
  swift: "Client.swift",
  ruby: "client.rb",
  go: "client.go",
  kotlin: "Client.kt",
};

/**
 * Renders the extended-language stub files.
 *
 * @param {{ artifact: object, invokeUrl: string|null, language: string, config: { packageName: string, version: string, className: string } }} input
 * @returns {Record<string, string>}
 */
export function generateExtendedFiles({ artifact, invokeUrl, language, config }) {
  const generator = GENERATOR_NAMES[language] ?? language;
  const operations = artifact?.protocol === "HTTP"
    ? (artifact.routes ?? []).length
    : (artifact.resources ?? []).reduce((count, resource) => count + Object.keys(resource.methods ?? {}).length, 0);
  const file = FILE_NAMES[language] ?? "client.txt";
  const stub = `// ${config.packageName} v${config.version} — Pods SDK stub (${language}).
//
// This ${language} client is generated with OpenAPI Generator
// (generator "${generator}", openapi-generator-cli ${OPENAPI_GENERATOR_VERSION};
// see workers/sdkgen/Dockerfile). The worker converts the stage OpenAPI
// export and renders the full client; this placeholder carries the operation
// count (${operations} operations) so jobs are traceable offline.
//
// Invoke URL: ${invokeUrl ?? "(none — pass a base URL override)"}
// Config: package=${config.packageName} version=${config.version} class=${config.className}
//
`;
  return {
    [file]: stub,
    "README.md": `# ${config.packageName} (${language})\n\nGenerated by Pods (S13 SDK) via OpenAPI Generator \`${generator}\` (openapi-generator-cli ${OPENAPI_GENERATOR_VERSION}). Run the worker: \`docker build -f workers/sdkgen/Dockerfile .\`. Base URL override, API key header (\`x-api-key\`), bearer token and SigV4 signing hook follow the generator defaults.\n`,
    "openapi-generator.txt": `generator=${generator}\nversion=${OPENAPI_GENERATOR_VERSION}\noperations=${operations}\n`,
  };
}
