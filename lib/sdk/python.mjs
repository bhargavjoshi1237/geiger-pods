/**
 * Python SDK generator (S13 part C, native).
 *
 * `requests`-based client, one method per operation. Supports base URL
 * override, API key header, bearer token, a SigV4 signing hook, timeouts and
 * retries on 429/5xx with backoff.
 *
 * @module lib/sdk/python
 */

import { groupSdkParams, listSdkOperations, sdkMethodName } from "./operations.mjs";

function pyName(name) {
  const snake = String(name).replace(/([a-z0-9])([A-Z])/g, "$1_$2").toLowerCase().replace(/[^a-z0-9_]+/g, "_");
  return /^[a-z_][a-z0-9_]*$/.test(snake) ? snake : `op_${snake}`;
}

/**
 * Renders the Python SDK files.
 *
 * @param {{ artifact: object, invokeUrl: string|null, config: { packageName: string, version: string, className: string } }} input
 * @returns {Record<string, string>}
 */
export function generatePythonFiles({ artifact, invokeUrl, config }) {
  const operations = listSdkOperations(artifact);
  const methods = [];
  for (const operation of operations) {
    const name = pyName(sdkMethodName(operation));
    const { path: pathParams } = groupSdkParams(operation.requestParameters);
    const hasBody = Object.keys(operation.requestModels ?? {}).length > 0;
    methods.push(`    def ${name}(self, params=None, headers=None, body=${hasBody ? "None" : "None"}):`);
    methods.push(`        """${operation.method} ${operation.path}."""`);
    if (pathParams.length > 0) {
      methods.push(`        params = dict(params or {})`);
      methods.push(`        for key in ${JSON.stringify(pathParams)}:`);
      methods.push(`            if params.get(key) is None:`);
      methods.push(`                raise ValueError("Missing path parameter \\"" + key + "\\".")`);
    }
    methods.push(`        path = ${JSON.stringify(operation.path)}`);
    if (pathParams.length > 0) {
      methods.push(`        for key in ${JSON.stringify(pathParams)}:`);
      methods.push(`            path = path.replace("{" + key + "}", quote(str(params.pop(key)), safe=""))`);
    }
    methods.push(`        return self._request(path, method=${JSON.stringify(operation.method)}, params=params, headers=headers, body=${hasBody ? "body" : "None"})`);
    methods.push(``);
  }

  const client = `"""${config.packageName} v${config.version} — generated by Pods (S13 SDK, python)."""
import time

import requests
from urllib.parse import quote


class ${config.className}:
    """requests-based client with retries on 429/5xx with backoff."""

    def __init__(self, base_url=None, api_key=None, bearer_token=None, sign_request=None, timeout=29, max_retries=2, session=None):
        self.base_url = (base_url or ${JSON.stringify(invokeUrl ?? "")}).rstrip("/")
        if not self.base_url:
            raise ValueError("A base_url is required.")
        self.api_key = api_key
        self.bearer_token = bearer_token
        self.sign_request = sign_request
        self.timeout = timeout
        self.max_retries = max_retries
        self.session = session or requests.Session()

    def _request(self, path, method="GET", params=None, headers=None, body=None):
        url = self.base_url + path
        attempt = 0
        while True:
            outgoing = dict(headers or {})
            if self.api_key:
                outgoing["x-api-key"] = self.api_key
            if self.bearer_token:
                outgoing["Authorization"] = "Bearer " + self.bearer_token
            kwargs = {"headers": outgoing, "timeout": self.timeout, "allow_redirects": False}
            if body is not None and method not in ("GET", "HEAD"):
                kwargs["json"] = body
            if params:
                kwargs["params"] = params
            if self.sign_request:
                kwargs = self.sign_request(url, kwargs) or kwargs
            response = self.session.request(method, url, **kwargs)
            # retries on 429/5xx with backoff (honors Retry-After).
            if (response.status_code == 429 or response.status_code >= 500) and attempt < self.max_retries:
                try:
                    wait = float(response.headers.get("Retry-After", "0"))
                except ValueError:
                    wait = 0.0
                delay = wait if wait > 0 else min(0.2 * (2 ** attempt), 5.0)
                time.sleep(delay)
                attempt += 1
                continue
            return response

${methods.join("\n")}`;
  return {
    "client.py": client,
    "pyproject.toml": `[project]\nname = "${config.packageName}"\nversion = "${config.version}"\ndescription = "Generated Pods SDK."\ndependencies = ["requests>=2.0"]\n`,
    "README.md": `# ${config.packageName}\n\nGenerated by Pods (S13 SDK, python). Base URL override: \`${config.className}(base_url=...)\`. API key: \`api_key\` sends \`x-api-key\`. Bearer: \`bearer_token\`. SigV4: pass \`sign_request\` from your ecosystem signer.\n`,
  };
}
