/**
 * TypeScript SDK generator (S13 part C, native).
 *
 * Typed models from the artifact schemas plus a fetch-based client with one
 * method per operation. Ships `client.ts` + `package.json` + `tsconfig.json`
 * so the acceptance test compiles it with the repo's own `tsc --noEmit`.
 *
 * @module lib/sdk/typescript
 */

import { groupSdkParams, listSdkOperations, sdkMethodName } from "./operations.mjs";

function tsTypeName(name) {
  const cleaned = String(name ?? "Model").replace(/[^A-Za-z0-9_]+/g, "_").replace(/^[0-9]+/, "");
  return /^[A-Za-z_][A-Za-z0-9_]*$/.test(cleaned) ? cleaned : "Model";
}

/**
 * Renders the TypeScript SDK files.
 *
 * @param {{ artifact: object, invokeUrl: string|null, config: { packageName: string, version: string, className: string } }} input
 * @returns {Record<string, string>}
 */
export function generateTypescriptFiles({ artifact, invokeUrl, config }) {
  const operations = listSdkOperations(artifact);
  const className = config.className;
  const models = artifact.models ?? {};

  const modelBlocks = [];
  for (const [name, entry] of Object.entries(models)) {
    const typeName = tsTypeName(name);
    const schema = entry?.schema ?? {};
    const props = schema.properties && typeof schema.properties === "object" ? schema.properties : {};
    const required = new Set(Array.isArray(schema.required) ? schema.required : []);
    const fields = Object.entries(props).map(([prop, sub]) => {
      const optional = required.has(prop) ? "" : "?";
      const type = sub?.type === "number" || sub?.type === "integer" ? "number"
        : sub?.type === "boolean" ? "boolean"
        : sub?.type === "array" ? "unknown[]"
        : sub?.type === "object" ? "Record<string, unknown>"
        : "unknown";
      return `  ${JSON.stringify(prop)}${optional}: ${type};`;
    });
    modelBlocks.push(`export interface ${typeName} {\n${fields.join("\n") || "  [key: string]: unknown;"}\n}`);
  }

  const methods = [];
  for (const operation of operations) {
    const name = sdkMethodName(operation);
    const { path: pathParams } = groupSdkParams(operation.requestParameters);
    const hasBody = Object.keys(operation.requestModels ?? {}).length > 0;
    const bodyType = hasBody ? "unknown" : "never";
    methods.push(`  async ${name}(input: OperationInput<${bodyType}> = {}, overrides: RequestOverrides = {}): Promise<Response> {`);
    methods.push(`    // ${operation.method} ${operation.path}`);
    if (pathParams.length > 0) {
      methods.push(`    for (const key of ${JSON.stringify(pathParams)} as string[]) {`);
      methods.push(`      if (input.params?.[key] === undefined) throw new Error(\`Missing path parameter "\${key}".\`);`);
      methods.push(`    }`);
    }
    methods.push(`    let resolvedPath: string = ${JSON.stringify(operation.path)};`);
    if (pathParams.length > 0) {
      methods.push(`    for (const key of ${JSON.stringify(pathParams)} as string[]) {`);
      methods.push(`      const raw = String((input.params as Record<string, unknown>)[key]);`);
      methods.push(`      resolvedPath = resolvedPath.replace(\`{\${key}}\`, encodeURIComponent(raw)).replace(\`{\${key}+}\`, raw.split("/").map(encodeURIComponent).join("/"));`);
      methods.push(`    }`);
    }
    methods.push(`    const query = new URLSearchParams();`);
    methods.push(`    for (const [key, value] of Object.entries(input.params ?? {})) {`);
    methods.push(`      if ((${JSON.stringify(pathParams)} as string[]).includes(key)) continue;`);
    methods.push(`      if (value === undefined || value === null) continue;`);
    methods.push(`      query.append(key, String(value));`);
    methods.push(`    }`);
    methods.push(`    const suffix = query.toString() ? \`?\${query}\` : "";`);
    methods.push(`    return this.request(resolvedPath + suffix, { method: ${JSON.stringify(operation.method)}, headers: input.headers, body: ${hasBody ? "input.body ?? null" : "null"} }, overrides);`);
    methods.push(`  }`);
    methods.push(``);
  }

  const client = `/**
 * ${config.packageName} v${config.version} — generated by Pods (S13 SDK).
 *
 * Typed models from the stage schemas plus a fetch-based client with one
 * method per operation. Supports base URL override, ApiKey header
 * (\`x-api-key\`), bearer token, a SigV4 signing hook, timeouts and retries
 * on 429/5xx with backoff.
 */
${modelBlocks.join("\n\n")}${modelBlocks.length > 0 ? "\n\n" : ""}
export interface OperationInput<TBody = unknown> {
  params?: Record<string, string | number | boolean | null | undefined>;
  headers?: Record<string, string>;
  body?: TBody | null;
}

export interface RequestOverrides {
  init?: RequestInit;
}

export type SignRequestHook = (init: { url: string } & RequestInit) => Promise<({ url: string } & RequestInit) | undefined | void>;

export class ${className} {
  private baseUrl: string;
  private apiKey: string | null;
  private bearerToken: string | null;
  private signRequest: SignRequestHook | null;
  private timeoutMs: number;
  private maxRetries: number;
  private fetchFn: typeof fetch;

  constructor(options: {
    baseUrl?: string;
    apiKey?: string | null;
    bearerToken?: string | null;
    signRequest?: SignRequestHook | null;
    timeoutMs?: number;
    maxRetries?: number;
    fetch?: typeof fetch;
  } = {}) {
    this.baseUrl = (options.baseUrl ?? ${JSON.stringify(invokeUrl ?? "")}).replace(/\\/+$/, "");
    if (!this.baseUrl) throw new Error("A baseUrl is required (pass { baseUrl } or regenerate with an invoke URL).");
    this.apiKey = options.apiKey ?? null;
    this.bearerToken = options.bearerToken ?? null;
    this.signRequest = options.signRequest ?? null;
    this.timeoutMs = Number.isInteger(options.timeoutMs) ? (options.timeoutMs as number) : 29000;
    this.maxRetries = Number.isInteger(options.maxRetries) ? (options.maxRetries as number) : 2;
    this.fetchFn = options.fetch ?? globalThis.fetch;
  }

  async request(path: string, op: { method?: string; headers?: Record<string, string>; body?: unknown } = {}, overrides: RequestOverrides = {}): Promise<Response> {
    const url: string = \`\${this.baseUrl}\${path}\`;
    let attempt = 0;
    for (;;) {
      const outgoing = new Headers(op.headers ?? {});
      if (this.apiKey) outgoing.set("x-api-key", this.apiKey);
      if (this.bearerToken) outgoing.set("authorization", \`Bearer \${this.bearerToken}\`);
      let init: RequestInit & { url?: string } = {
        method: op.method ?? "GET",
        headers: outgoing,
        signal: AbortSignal.timeout(this.timeoutMs),
        redirect: "manual",
      };
      const body = op.body as unknown;
      if (body !== null && body !== undefined && (op.method ?? "GET") !== "GET" && (op.method ?? "GET") !== "HEAD") {
        init.body = typeof body === "string" ? body : JSON.stringify(body);
        if (!outgoing.has("content-type")) outgoing.set("content-type", "application/json");
      }
      if (this.signRequest) init = ((await this.signRequest({ url, ...init })) as RequestInit & { url?: string }) ?? init;
      Object.assign(init, overrides.init ?? {});
      const response: Response = await this.fetchFn(url, init);
      // retries on 429/5xx with backoff (honors Retry-After).
      if ((response.status === 429 || response.status >= 500) && attempt < this.maxRetries) {
        const retryAfter = Number(response.headers.get("retry-after") ?? "0");
        const backoff = Number.isFinite(retryAfter) && retryAfter > 0 ? retryAfter * 1000 : 200 * 2 ** attempt;
        await new Promise((resolve) => setTimeout(resolve, Math.min(backoff, 5000)));
        attempt += 1;
        continue;
      }
      return response;
    }
  }

${methods.join("\n")}}
`;
  return {
    "client.ts": client,
    "package.json": `${JSON.stringify({ name: config.packageName, version: config.version, type: "module", main: "client.ts" }, null, 2)}\n`,
    "tsconfig.json": `${JSON.stringify({ compilerOptions: { target: "ES2022", module: "NodeNext", moduleResolution: "NodeNext", strict: true, skipLibCheck: true, noEmit: true }, include: ["client.ts"] }, null, 2)}\n`,
    "README.md": `# ${config.packageName}\n\nGenerated by Pods (S13 SDK, typescript). Compile: \`tsc --noEmit\`. Base URL override: \`new ${className}({ baseUrl })\`. ApiKey: \`{ apiKey }\` sends \`x-api-key\`. Bearer: \`{ bearerToken }\`. SigV4: pass \`signRequest\` from your ecosystem signer.\n`,
  };
}
